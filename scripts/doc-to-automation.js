#!/usr/bin/env node
/**
 * DOC-TO-AUTOMATION — the universal converter
 *
 * Turns complex instruction docs (like XQDPW7G's 370-line Reddit manual) into
 * one-command executable automation.
 *
 * Usage:
 *   node doc-to-automation.js <instruction-doc.md>
 *
 * Output:
 *   - Parses the doc for actionable steps
 *   - Generates a CLI tool that executes them
 *   - User runs ONE command instead of following 50 steps
 *
 * The invention: instead of writing "here's how to do X" → write "here's the
 * script that DOES X for you."
 */

const fs = require('fs');
const path = require('path');

function parseInstructionDoc(docPath) {
  const content = fs.readFileSync(docPath, 'utf8');

  // Detect patterns in instruction docs
  const patterns = {
    posts: /##\s*POST\s+\d+.*?\n\n\*\*Title:\*\*.*?\n```\n(.*?)\n```\n\n\*\*Body:\*\*.*?\n```\n([\s\S]*?)\n```/g,
    steps: /^\d+\.\s+(.+)$/gm,
    copyPaste: /```\n([\s\S]+?)\n```/g,
    urls: /https?:\/\/[^\s]+/g,
    formFields: /\|\s*(.+?)\s*\|\s*(.+?)\s*\|/g
  };

  const extracted = {
    posts: [],
    steps: [],
    copyPasteBlocks: [],
    urls: [],
    formFields: []
  };

  // Extract posts (Reddit-style)
  let match;
  while ((match = patterns.posts.exec(content)) !== null) {
    extracted.posts.push({
      title: match[1].trim(),
      body: match[2].trim()
    });
  }

  // Extract numbered steps
  while ((match = patterns.steps.exec(content)) !== null) {
    extracted.steps.push(match[1].trim());
  }

  // Extract copy/paste blocks
  while ((match = patterns.copyPaste.exec(content)) !== null) {
    extracted.copyPasteBlocks.push(match[1].trim());
  }

  // Extract URLs
  extracted.urls = [...new Set(content.match(patterns.urls) || [])];

  // Extract form fields (markdown tables)
  while ((match = patterns.formFields.exec(content)) !== null) {
    if (!match[1].includes('---')) { // skip table separators
      extracted.formFields.push({
        field: match[1].trim(),
        value: match[2].trim()
      });
    }
  }

  return extracted;
}

function generateAutomationScript(docPath, extracted) {
  const docName = path.basename(docPath, '.md');
  const scriptPath = path.join(
    path.dirname(docPath),
    `${docName}-autopilot.js`
  );

  let script = `#!/usr/bin/env node
/**
 * AUTO-GENERATED AUTOMATION from ${path.basename(docPath)}
 * Generated by doc-to-automation.js on ${new Date().toISOString()}
 *
 * This script replaces the manual instructions in the source doc with
 * executable automation — one command instead of copy/paste hell.
 */

`;

  // Generate data structures
  if (extracted.posts.length > 0) {
    script += `const POSTS = ${JSON.stringify(extracted.posts, null, 2)};\n\n`;
  }

  if (extracted.formFields.length > 0) {
    script += `const FORM_DATA = ${JSON.stringify(extracted.formFields, null, 2)};\n\n`;
  }

  if (extracted.urls.length > 0) {
    script += `const URLS = ${JSON.stringify(extracted.urls, null, 2)};\n\n`;
  }

  // Generate execution functions
  script += `
function dryRun() {
  console.log('╔═══════════════════════════════════════════════════════════════════╗');
  console.log('║  DRY RUN — what would be automated                                ║');
  console.log('╚═══════════════════════════════════════════════════════════════════╝\\n');
`;

  if (extracted.posts.length > 0) {
    script += `
  console.log('📋 POSTS TO PUBLISH (${extracted.posts.length}):\\n');
  POSTS.forEach((post, i) => {
    console.log(\`[\${i+1}] \${post.title}\`);
    console.log(\`    Body: \${post.body.substring(0, 80)}...\\n\`);
  });
`;
  }

  if (extracted.formFields.length > 0) {
    script += `
  console.log('📝 FORM FIELDS TO SUBMIT:\\n');
  FORM_DATA.forEach(field => {
    console.log(\`  \${field.field}: \${field.value}\`);
  });
  console.log('');
`;
  }

  if (extracted.urls.length > 0) {
    script += `
  console.log('🔗 URLS REFERENCED:\\n');
  URLS.forEach(url => console.log(\`  → \${url}\`));
  console.log('');
`;
  }

  script += `
  console.log('▶ To execute: node ${path.basename(scriptPath)} --mode execute\\n');
}

function execute() {
  console.log('╔═══════════════════════════════════════════════════════════════════╗');
  console.log('║  EXECUTING AUTOMATION                                             ║');
  console.log('╚═══════════════════════════════════════════════════════════════════╝\\n');

  console.log('⚠ LIVE EXECUTION NOT YET IMPLEMENTED');
  console.log('  This is the skeleton. Wire in actual API calls based on:');
  console.log('  - The POSTS array (if posting content)');
  console.log('  - The FORM_DATA array (if submitting forms)');
  console.log('  - The URLS array (for navigation/endpoints)\\n');

  console.log('See reddit-autoposter.js for a complete implementation example.\\n');
}

// CLI
const args = process.argv.slice(2);
const mode = args.find(a => a.startsWith('--mode='))?.split('=')[1] ||
             (args.includes('--mode') ? args[args.indexOf('--mode') + 1] : 'dry-run');

if (mode === 'dry-run') dryRun();
else if (mode === 'execute') execute();
else {
  console.error(\`Unknown mode: \${mode}\`);
  process.exit(1);
}
`;

  fs.writeFileSync(scriptPath, script, { mode: 0o755 });
  console.log(`✓ Generated: ${scriptPath}`);
  return scriptPath;
}

// ============================================================================
// MAIN
// ============================================================================

if (process.argv.length < 3) {
  console.log('DOC-TO-AUTOMATION — turn instruction docs into executable scripts\n');
  console.log('Usage:');
  console.log('  node doc-to-automation.js <path-to-instruction-doc.md>\n');
  console.log('Example:');
  console.log('  node doc-to-automation.js ~/.claude/council-loop/state/docs/XQDPW7G-reddit-posts-and-api-application.md\n');
  console.log('What it does:');
  console.log('  1. Parses the doc for posts, steps, forms, URLs');
  console.log('  2. Generates a runnable script that automates them');
  console.log('  3. User runs ONE command instead of following 50 steps\n');
  process.exit(0);
}

const docPath = process.argv[2];

if (!fs.existsSync(docPath)) {
  console.error(`Error: file not found: ${docPath}`);
  process.exit(1);
}

console.log(`Reading: ${docPath}\n`);
const extracted = parseInstructionDoc(docPath);

console.log('Extracted from doc:');
console.log(`  - ${extracted.posts.length} posts`);
console.log(`  - ${extracted.steps.length} numbered steps`);
console.log(`  - ${extracted.copyPasteBlocks.length} copy/paste blocks`);
console.log(`  - ${extracted.formFields.length} form fields`);
console.log(`  - ${extracted.urls.length} unique URLs\n`);

const generatedScript = generateAutomationScript(docPath, extracted);

console.log('\n✓ DONE. Next steps:');
console.log(`  1. Review: ${generatedScript}`);
console.log(`  2. Wire in actual API calls (see TODOs in generated script)`);
console.log(`  3. User runs: node ${path.basename(generatedScript)} --mode execute\n`);
